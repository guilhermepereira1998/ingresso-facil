begin;
create table if not exists public.eventos (
 id integer generated by default as identity primary key,
 nome varchar not null, data date not null, capacidade integer not null
);
create table if not exists public.participantes (
 id integer generated by default as identity primary key,
 nome varchar not null, email varchar not null unique
);
create table if not exists public.ingressos (
 id integer generated by default as identity primary key,
 evento_id integer not null references public.eventos(id),
 participante_id integer not null references public.participantes(id),
 codigo varchar not null unique, utilizado boolean not null default false,
 constraint uq_evento_participante unique(evento_id,participante_id)
);
alter table public.eventos enable row level security;
alter table public.participantes enable row level security;
alter table public.ingressos enable row level security;
commit;
select tablename, rowsecurity from pg_tables where schemaname='public' and tablename in ('eventos','participantes','ingressos');
